#!/usr/bin/env bash
# -------------------------------------------------------------------------
# Serve USAM Communities over HTTPS on ports 80/443 under its OWN hostname,
# next to any existing site on the same server (USAM Hub keeps answering on
# the bare IP / its own names - its Nginx files are not modified).
#
#   sudo bash deploy/enable-https.sh                       # uses <ip>.sslip.io
#   sudo DOMAIN=communities.example.com EMAIL=you@x.com bash deploy/enable-https.sh
#
# Without your own domain it uses <a-b-c-d>.sslip.io, a public wildcard DNS
# name that always resolves to the IP inside it - enough for a real Let's
# Encrypt certificate. Re-run later with DOMAIN=... once your DNS points here.
#
# Steps: HTTP-01 challenge site -> certbot (webroot, auto-renew + nginx reload)
# -> HTTPS site -> app switched to production HTTPS settings (staging flag
# removed, secure cookies) -> :8080 redirects to the HTTPS URL.
# Every Nginx change is gated by `nginx -t`; on failure the new file is
# removed and Nginx is left exactly as it was.
# -------------------------------------------------------------------------
set -euo pipefail
[ "$(id -u)" -eq 0 ] || { echo "Run with sudo." >&2; exit 1; }
ENV_FILE=/etc/usam-communities/env
SVC=usam-communities
WEBROOT=/var/www/usam-communities-acme
SITE=/etc/nginx/sites-available/usam-communities-https.conf
# "zz-" so it loads AFTER the existing sites: Nginx makes the first server block
# on a port the default for unmatched names (e.g. the bare IP), and that must
# stay the existing site (USAM Hub), not this one.
LINK=/etc/nginx/sites-enabled/zz-usam-communities-https.conf
log() { printf '\n\033[1;32m==> %s\033[0m\n' "$*"; }
die() { printf '\n\033[1;31mERROR: %s\033[0m\n' "$*" >&2; exit 1; }
[ -f "$ENV_FILE" ] || die "Run deploy/install-alongside.sh first."
APP_PORT="$(grep '^PORT=' "$ENV_FILE" | cut -d= -f2)"
[ -n "$APP_PORT" ] || die "PORT missing in $ENV_FILE"

IP="$(TOKEN=$(curl -fsS -m 3 -X PUT http://169.254.169.254/latest/api/token -H 'X-aws-ec2-metadata-token-ttl-seconds: 60') \
      && curl -fsS -m 3 -H "X-aws-ec2-metadata-token: $TOKEN" http://169.254.169.254/latest/meta-data/public-ipv4 || true)"
[ -n "$IP" ] || IP="$(curl -fsS -m 5 https://checkip.amazonaws.com | tr -d '\n')"
DOMAIN="${DOMAIN:-$(echo "$IP" | tr . -).sslip.io}"
log "Hostname: $DOMAIN (server IP $IP)"
RESOLVED="$(getent ahostsv4 "$DOMAIN" | awk 'NR==1{print $1}')"
[ "$RESOLVED" = "$IP" ] || die "$DOMAIN resolves to '${RESOLVED:-nothing}', not $IP. Point its DNS A record at $IP first."

nginx_apply() { # validate or roll back the new site file
  ln -sf "$SITE" "$LINK"
  if ! nginx -t 2>/tmp/usamc-nginx.txt; then
    cat /tmp/usamc-nginx.txt; rm -f "$LINK"
    die "Nginx rejected the new config; it was removed and Nginx is unchanged."
  fi
  systemctl reload nginx
}

# ---- 1. HTTP site for the ACME challenge (port 80, this hostname only) -----
log "Installing certbot (no system upgrade)"
apt-get install -y --no-upgrade --no-install-recommends certbot >/dev/null
install -d -m 755 "$WEBROOT"
cat > "$SITE" <<EOF
# USAM Communities HTTPS site for $DOMAIN (generated by enable-https.sh)
server {
    listen 80;
    listen [::]:80;
    server_name $DOMAIN;
    server_tokens off;
    location /.well-known/acme-challenge/ { root $WEBROOT; }
    location / { return 404; }
}
EOF
nginx_apply

# ---- 2. Certificate (auto-renews; Nginx reloads after each renewal) --------
if [ ! -f "/etc/letsencrypt/live/$DOMAIN/fullchain.pem" ]; then
  log "Requesting a Let's Encrypt certificate for $DOMAIN"
  if [ -n "${EMAIL:-}" ]; then REG=(--email "$EMAIL"); else REG=(--register-unsafely-without-email); fi
  certbot certonly --webroot -w "$WEBROOT" -d "$DOMAIN" --non-interactive --agree-tos \
    "${REG[@]}" --deploy-hook "systemctl reload nginx" \
    || die "certbot failed (is port 80 reachable from the internet for $DOMAIN?)"
else
  log "Certificate for $DOMAIN already present"
fi

# ---- 3. Full HTTPS site ---------------------------------------------------
cat > "$SITE" <<EOF
# USAM Communities HTTPS site for $DOMAIN (generated by enable-https.sh)
# Uses the upstream / rate-limit zones / log format defined in
# usam-communities.conf (install-alongside.sh).
server {
    listen 80;
    listen [::]:80;
    server_name $DOMAIN;
    server_tokens off;
    location /.well-known/acme-challenge/ { root $WEBROOT; }
    location / { return 301 https://\$host\$request_uri; }
}
server {
    listen 443 ssl;
    listen [::]:443 ssl;
    http2 on;
    server_name $DOMAIN;
    server_tokens off;
    ssl_certificate     /etc/letsencrypt/live/$DOMAIN/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/$DOMAIN/privkey.pem;
    ssl_protocols TLSv1.2 TLSv1.3;
    ssl_prefer_server_ciphers off;
    ssl_session_cache shared:usamc_tls:10m;
    ssl_session_timeout 1d;
    add_header Strict-Transport-Security "max-age=31536000" always;
    proxy_hide_header Strict-Transport-Security;
    client_max_body_size 256k;
    access_log /var/log/nginx/usam-communities.access.log usam_communities;
    error_log  /var/log/nginx/usam-communities.error.log warn;
    proxy_http_version 1.1;
    proxy_set_header Connection "";
    proxy_set_header Host \$host;
    proxy_set_header X-Forwarded-For \$remote_addr;
    proxy_set_header X-Forwarded-Proto https;
    proxy_set_header X-Request-Id \$request_id;
    proxy_read_timeout 60s;
    location ~ /\.(?!well-known) { return 404; }
    location ~ ^/api/v1/auth/(login|signup|password/forgot|password/reset|verify-email|resend-verification)\$ {
        limit_req zone=usamc_auth burst=10 nodelay;
        limit_req_status 429;
        proxy_pass http://usam_communities_app;
    }
    location ~ ^/api/v1/(users/me/avatar|media/images)\$ {
        client_max_body_size 15m;
        limit_req zone=usamc_api burst=5 nodelay;
        proxy_pass http://usam_communities_app;
    }
    location = /api/v1/stream {
        proxy_buffering off;
        proxy_read_timeout 1h;
        proxy_pass http://usam_communities_app;
    }
    location /api/ {
        limit_req zone=usamc_api burst=40 nodelay;
        limit_req_status 429;
        proxy_pass http://usam_communities_app;
    }
    location / { proxy_pass http://usam_communities_app; }
}
EOF
nginx_apply
log "HTTPS site live for $DOMAIN"

# ---- 4. Switch the app to HTTPS production settings ------------------------
cp -p "$ENV_FILE" "$ENV_FILE.bak-$(date +%Y%m%d-%H%M%S)"
ORIGIN="https://$DOMAIN"
sed -i \
  -e "s#^APP_ORIGIN=.*#APP_ORIGIN=$ORIGIN#" \
  -e "s#^FRONTEND_URL=.*#FRONTEND_URL=$ORIGIN#" \
  -e "s#^COOKIE_SECURE=.*#COOKIE_SECURE=true#" \
  -e "/^STAGING_INSECURE_HTTP=/d" \
  "$ENV_FILE"
systemctl restart "$SVC"
for i in $(seq 1 30); do
  curl -fsS "http://127.0.0.1:$APP_PORT/api/v1/health" >/dev/null 2>&1 && break; sleep 1
done
curl -fsS "http://127.0.0.1:$APP_PORT/api/v1/health" >/dev/null 2>&1 \
  || { journalctl -u "$SVC" -n 60 --no-pager; die "app did not restart cleanly (previous env saved as $ENV_FILE.bak-*)"; }

# ---- 5. Old :8080 entry point now redirects to HTTPS -----------------------
OLD=/etc/nginx/sites-available/usam-communities.conf
if [ -f "$OLD" ] && ! grep -q "return 301 $ORIGIN" "$OLD"; then
  cp -p "$OLD" "$OLD.bak-$(date +%Y%m%d-%H%M%S)"
  # Keep the shared definitions (log format, zones, upstream); replace the server block.
  sed -n '1,/^server {/p' "$OLD" | sed '$d' > "$OLD.new"
  cat >> "$OLD.new" <<EOF
server {
    listen 8080;
    listen [::]:8080;
    server_name _;
    server_tokens off;
    return 301 $ORIGIN\$request_uri;
}
EOF
  mv "$OLD.new" "$OLD"
  nginx -t 2>/dev/null && systemctl reload nginx || { cp -p "$(ls -1t "$OLD".bak-* | head -1)" "$OLD"; systemctl reload nginx; }
fi

# ---- 6. Verify ----------------------------------------------------------------
HEALTH="$(curl -fsS --resolve "$DOMAIN:443:127.0.0.1" "https://$DOMAIN/api/v1/health" || true)"
CODE="$(curl -s -o /dev/null -w '%{http_code}' --resolve "$DOMAIN:443:127.0.0.1" "https://$DOMAIN/")"
echo
echo "------------------------------------------------------------------"
echo " USAM Communities is now served over HTTPS"
echo "   URL            : $ORIGIN"
echo "   health (https) : $HEALTH"
echo "   home page      : HTTP $CODE"
echo "   certificate    : /etc/letsencrypt/live/$DOMAIN (auto-renews)"
echo "   staging flag   : removed; secure cookies on"
echo "------------------------------------------------------------------"
