// Generates API_DOCUMENTATION.md from the real source, so it cannot drift.
//   node scripts/gen-api-docs.mjs [outputPath]      (npm run docs:api)
// Routes + their guards (auth / role / verified-email / feature-flag / limiter)
// are read from the server modules; the count is cross-checked against the live
// Express router and the script FAILS if they disagree (catches regex misses).
import fs from "node:fs";
import path from "node:path";

process.env.NODE_ENV = "test";
process.env.DB_DIALECT = "sqlite";
process.env.SQLITE_PATH = path.join(process.env.TEMP || "/tmp", "usam-docgen.sqlite");
const { default: app } = await import("../server/index.js");

const out = process.argv[2] || path.resolve("docs", "API_DOCUMENTATION.md");
const files = ["index.js", "identity.js", "payments.js", "media.js", "account.js", "mfa.js"];
// The chunk after the path ends at the handler: an inline `async (` / `(req`,
// or - for routes registered with a named handler - the closing `);`.
const re = /app\.(get|post|put|patch|delete)\(\s*"(\/[^"]*)"([\s\S]*?)(?=async\s*\(|\(\s*req\s*,\s*res|\(req\s*,|\)\s*;)/g;
const routes = [];
for (const f of files) {
  const src = fs.readFileSync(path.join("server", f), "utf8");
  for (const m of src.matchAll(re)) {
    const [, method, p, chunk] = m;
    if (!p.startsWith("/api/")) continue;
    const mw = chunk.split(",").map((s) => s.trim()).filter(Boolean);
    const has = (n) => mw.some((x) => x === n || x.startsWith(n + "("));
    routes.push({
      method: method.toUpperCase(),
      path: p,
      access: has("superAdmin") ? "super_admin" : has("admin") ? "admin+" : has("moderator") ? "moderator+" : has("auth") ? "signed-in" : "public",
      verified: has("requireVerified"),
      flag: mw.find((x) => x.startsWith("requireFlag"))?.match(/"([^"]+)"/)?.[1] || "",
      limits: mw.filter((x) => /Limit(er)?$/.test(x)).join(", "),
    });
  }
}
// De-duplicate (e.g. the contact route is declared twice: limiter + handler).
const seen = new Set();
const unique = routes.filter((r) => !seen.has(r.method + r.path) && seen.add(r.method + r.path));

// Cross-check against the live Express router.
const live = new Set();
(function walk(stack) {
  for (const layer of stack) {
    if (layer.route) for (const m of Object.keys(layer.route.methods)) if (typeof layer.route.path === "string" && layer.route.path.startsWith("/api/")) live.add(m.toUpperCase() + layer.route.path);
    else if (layer.handle?.stack) walk(layer.handle.stack);
  }
})(app.router.stack);
const missing = [...live].filter((k) => !seen.has(k));
if (missing.length) {
  console.error("Router has routes the doc generator did not parse:\n" + missing.join("\n"));
  process.exit(1);
}

const domains = [
  ["auth", "Authentication & account recovery"],
  ["users", "Own account: security, sessions, avatar, export, deletion"],
  ["me", "Current member: profile, summary, network, memberships"],
  ["communities", "Communities"],
  ["posts", "Posts, comments, reactions, bookmarks"],
  ["saved", "Saved posts"],
  ["reports", "Content reports"],
  ["members", "Member directory, follows, blocks"],
  ["messages", "Direct messages"],
  ["search", "Search"],
  ["saved-searches", "Saved searches"],
  ["notifications", "Notifications"],
  ["notification-preferences", "Notification preferences"],
  ["events", "Events, registration, tickets"],
  ["my-events", "My events"],
  ["challenges", "Challenges"],
  ["my-submissions", "My challenge submissions"],
  ["mentors", "Mentors"],
  ["mentorship", "Mentorship requests"],
  ["offers", "Offers"],
  ["perks", "Perks"],
  ["my-perk-applications", "My perk applications"],
  ["organizations", "Organizations & teams"],
  ["partnerships", "Partnerships"],
  ["groups", "Groups & chapters"],
  ["curated-rooms", "Curated rooms"],
  ["room-applications", "Room applications"],
  ["plans", "Plans (public)"],
  ["billing", "Billing"],
  ["subscriptions", "Subscriptions"],
  ["payments", "Payments (Paymob)"],
  ["activity", "Activity feed"],
  ["platform-config", "Platform configuration (flags + CMS content)"],
  ["contact", "Contact form"],
  ["health", "Health"],
  ["admin", "Administration"],
];
const seg = (p) => p.replace(/^\/api\/v1\//, "").split("/")[0];
const groups = new Map(domains.map(([k]) => [k, []]));
for (const r of unique) (groups.get(seg(r.path)) || groups.set(seg(r.path), []).get(seg(r.path))).push(r);

let md = `<!-- GENERATED by scripts/gen-api-docs.mjs from the server source. Do not edit by hand: run \`npm run docs:api\`. -->
# USAM Communities - API Documentation

Generated: ${new Date().toISOString().slice(0, 10)} · **${unique.length} endpoints** under \`/api/v1\`

## 1. Conventions

**Base URL** \`https://<domain>/api/v1\` · all bodies are JSON (\`Content-Type: application/json\`).
A request with a missing/incorrect Content-Type is answered with a 4xx, never a 5xx.

**Authentication.** An opaque, \`HttpOnly\`, \`SameSite=Lax\` session cookie \`usam_session\` (30 days; only its SHA-256 is stored server-side). There are no bearer tokens. Sign in with \`POST /auth/login\`; the cookie is set by the server.

**Roles.** \`member < moderator < admin < super_admin\`. "Access" below is the *minimum* role. "admin+" includes super_admin; "moderator+" includes admin and super_admin.
**Verified email.** Routes flagged *verified* return \`403 email_verification_required\` until the member verifies their email (when \`REQUIRE_EMAIL_VERIFICATION=true\`).
**Feature flags.** Routes with a flag return \`403 feature_disabled\` when an admin switches that flag off (a flag that was never created counts as on).

**CSRF.** Every non-GET request whose \`Origin\` header does not match the app origin is rejected with \`403 origin_rejected\`. Combined with SameSite=Lax cookies and JSON-only bodies.

**Errors.** Always \`{ "error": "machine_readable_code" }\` with a meaningful HTTP status: \`400\` validation · \`401 sign_in_required\` · \`403 forbidden\` (and the codes above) · \`404 not_found\` (also returned for malformed ids) · \`409\` conflict/state · \`413 payload_too_large\` · \`429 too_many_requests\` · \`502\` upstream payment/provider failure · \`503\` database unavailable.
Internal details are never returned; unexpected faults are \`500 internal_error\` and logged with a \`requestId\`.

**Tracing.** Every response carries \`X-Request-Id\`; send your own (\`[A-Za-z0-9._-]{8,64}\`) to correlate.

**Rate limiting.** Responses include \`RateLimit-Limit\`, \`RateLimit-Remaining\`, \`RateLimit-Reset\`; a throttled call returns \`429\` with \`Retry-After\`. Limits (per IP unless noted): API 600/min · credential endpoints 30/15 min per IP+email · password-reset emails 3/hour per target address · verification emails 6/hour per user · writes 120/min per user · payment init 20/10 min per user. All are environment-tunable.

**Pagination.** List endpoints are capped. Admin lists use \`?page=1&pageSize=25\` (max 100) and return \`{ items, page, pageSize, total, totalPages }\`. Feed/search/directory endpoints return the newest N items (feed 30, search 10 per type, members 50).

**Idempotency.** \`POST /subscriptions\` for a paid plan **requires** an \`Idempotency-Key\` header (>= 12 chars). Replaying the same key returns the same subscription/payment attempt and reuses the provider order - it never creates a second charge.

**IDs.** All primary keys are UUIDs. A malformed id in a path returns \`404 not_found\`.

## 2. Key flows (examples)

### Sign up -> verify -> sign in
\`\`\`http
POST /api/v1/auth/signup
{ "name": "Sara Ali", "email": "sara@example.com", "password": "correct-horse-9", "persona": "launchpad" }
-> 201 { "user": { "id": "...", "role": "member", "emailVerified": false, ... } }   (+ Set-Cookie, verification email queued)

POST /api/v1/auth/verify-email        { "token": "<from the emailed link>" }   -> 200 { "ok": true, "verified": true }
POST /api/v1/auth/login               { "email": "...", "password": "..." }    -> 200 { "user": {...} }
\`\`\`
Password policy: 10-200 characters with at least one letter and one digit. After 10 consecutive failures an account is locked for 15 minutes.

### Paid subscription (Paymob hosted checkout)
\`\`\`http
POST /api/v1/subscriptions
Idempotency-Key: 6f0c2b9e-...-unique-per-attempt
{ "planCode": "plus", "billingCycle": "monthly" }
-> 202 { "subscriptionId": "...", "paymentAttemptId": "...", "status": "pending_payment",
         "amountEgp": 149, "currency": "EGP",
         "checkout": { "provider": "paymob", "configured": true, "checkoutUrl": "https://accept.paymob.com/..." } }
\`\`\`
The price always comes from the \`Plan\` row, never from the client. The subscription stays \`pending_payment\` and grants **no entitlement** until Paymob's signed webhook confirms the exact amount. When Paymob is not configured, \`checkout.configured\` is \`false\` and nothing is charged.

### Paymob webhook (server-to-server)
\`\`\`http
POST /api/v1/payments/webhook/paymob?hmac=<sha512 hex>
{ "type": "TRANSACTION", "obj": { "id": 123, "amount_cents": 14900, "currency": "EGP", "success": true, "order": { "merchant_order_id": "usam-<attemptId>" }, ... } }
\`\`\`
The HMAC-SHA512 is verified in constant time. Then: duplicates are ignored (unique provider+transaction id), a mismatched amount/currency is **refused and flagged**, pending callbacks change nothing, a late failure cannot downgrade a paid attempt, and a refunded payment can never be re-activated.

### Avatar upload
\`\`\`http
POST /api/v1/users/me/avatar      { "image": "data:image/jpeg;base64,/9j/4AAQ..." }   -> 200 { "avatarUrl": "..." }
\`\`\`
Accepted: PNG, JPEG, WebP, GIF. The bytes are checked against the declared type (magic numbers); SVG and disguised content are rejected \`400 invalid_image\`. Max size \`MAX_UPLOAD_BYTES\` (default 10 MB).

### Admin: change a price without a deploy
\`\`\`http
PATCH /api/v1/admin/plans/:id   { "monthlyEgp": 179 }   -> 200 { "ok": true }     (audited; /plans reflects it immediately)
\`\`\`

## 3. Endpoint reference
Legend - **Access**: minimum role · **Verified**: needs a verified email · **Flag**: feature flag that can disable it · **Limiter**: extra route-specific throttle.
`;

for (const [key, title] of [...domains, ...[...groups.keys()].filter((k) => !domains.some(([d]) => d === k)).map((k) => [k, k])]) {
  const rs = groups.get(key);
  if (!rs?.length) continue;
  md += `\n### ${title}\n\n| Method | Path | Access | Verified | Flag | Limiter |\n|---|---|---|---|---|---|\n`;
  for (const r of rs.sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method)))
    md += `| ${r.method} | \`${r.path.replace("/api/v1", "")}\` | ${r.access} | ${r.verified ? "yes" : ""} | ${r.flag} | ${r.limits} |\n`;
}
md += `
## 4. Notes
- \`GET /auth/verify-email/:token\` exists for compatibility; the web app completes verification with \`POST /auth/verify-email\` so mail scanners that merely fetch the link cannot consume the single-use token.
- \`/me/groups\` and \`/me/room-applications\` overlap with data also embedded in \`/groups\` and \`/curated-rooms\`; they are kept for API stability and power the profile's "My connections" card.
- \`/health\` and \`/payments/webhook/paymob\` are infrastructure endpoints with no UI by design.
`;
fs.writeFileSync(out, md);
console.log(`wrote ${out} (${unique.length} endpoints; router has ${live.size})`);
process.exit(0);
